import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, stat } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const themeRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const readText = (path) => readFile(join(themeRoot, path), 'utf8');
const packageJson = JSON.parse(await readText('package.json'));
const skin = JSON.parse(await readText('skin.json'));
const sources = JSON.parse(await readText('assets/source.json'));
const patch = await readText('cordis.patch.yml');
const bundle = await readText('lib/client.js');

const expectedPackage = '@dsh-external/dsh-client-ui-skin-wuthering-aemeath';
assert.equal(packageJson.name, expectedPackage);
assert.equal(packageJson.exports['./client'], './lib/client.js');
assert.equal(skin.package, expectedPackage);
assert.equal(skin.bodyAttr, 'data-dsh-skin-aemeath');
assert.match(patch, /id: ui-skin-wuthering-aemeath/);
assert.ok(patch.includes(`name: '${expectedPackage}'`));
assert.ok(bundle.startsWith('// Generated by scripts/build-client.mjs.'));
assert.ok(bundle.includes(`id: "${expectedPackage}"`));
assert.ok(bundle.includes('window.__ModuleLoader__.load'));
assert.ok(bundle.includes('ctx.effect('));
assert.ok(bundle.includes('observer.disconnect()'));
assert.ok(bundle.includes("body.removeAttribute(AEMEATH_BODY_ATTR)"));
assert.equal((bundle.match(/data:image\/png;base64,/g) ?? []).length, 3);

for (const asset of sources.assets) {
  assert.match(asset.url, /^https:\/\/prod-alicdn-community\.kurobbs\.com\//);
  const assetPath = join(themeRoot, 'assets', asset.file);
  const details = await stat(assetPath);
  assert.ok(details.size > 100_000, `${asset.file} is unexpectedly small`);
}

const digest = createHash('sha256').update(bundle).digest('hex').slice(0, 16);
console.log(`Verified ${skin.name}: bundle ${bundle.length.toLocaleString()} chars, sha256 ${digest}`);
