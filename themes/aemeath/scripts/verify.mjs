let assetRoute;
hostModule.apply({
  effect: (register) => register(),
  webServer: {
    register: (route) => {
      assetRoute = route;
      return () => {};
    },
  },
});
assert.equal(assetRoute.kind, 'prefix');
assert.match(assetRoute.path, /\/assets$/);

const requestAsset = async (method, url) => {
  const response = {
    body: undefined,
    headers: undefined,
    status: undefined,
    end(body) {
      this.body = body;
    },
    writeHead(status, headers = {}) {
      this.status = status;
      this.headers = headers;
    },
  };
  await assetRoute.handler({ method, url }, response);
  return response;
};

for (const asset of sources.assets) {
  const response = await requestAsset('GET', `${assetRoute.path}/${asset.optimizedFile}?rev=verify`);
  assert.equal(response.status, 200);
  assert.equal(response.headers['content-type'], 'image/webp');
  assert.equal(response.headers['cache-control'], 'public, max-age=31536000, immutable');
  assert.equal(response.headers['content-length'], response.body.length);
  assert.equal(response.body.subarray(0, 4).toString('ascii'), 'RIFF');
}

assert.equal((await requestAsset('HEAD', `${assetRoute.path}/${sources.assets[0].optimizedFile}`)).body, undefined);
assert.equal((await requestAsset('GET', `${assetRoute.path}/missing.webp`)).status, 404);
assert.equal((await requestAsset('POST', `${assetRoute.path}/${sources.assets[0].optimizedFile}`)).status, 405);

