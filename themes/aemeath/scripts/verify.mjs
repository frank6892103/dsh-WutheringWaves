for (const previewPath of Object.values(skin.preview)) {
  const preview = await readFile(join(themeRoot, previewPath));
  assert.ok(preview.length > 20_000, `${previewPath} is unexpectedly small`);
  assert.equal(preview.subarray(0, 4).toString('ascii'), 'RIFF');
  assert.equal(preview.subarray(8, 12).toString('ascii'), 'WEBP');
}

for (const asset of sources.assets) {
  assert.match(asset.url, /^https:\/\/prod-alicdn-community\.kurobbs\.com\//);
  const assetPath = join(themeRoot, 'assets', asset.file);
  const details = await stat(assetPath);
  assert.ok(details.size > 100_000, `${asset.file} is unexpectedly small`);

  assert.match(asset.optimizedFile, /\.webp$/);
  const optimized = await readFile(join(themeRoot, 'assets', asset.optimizedFile));
  assert.equal(optimized.subarray(0, 4).toString('ascii'), 'RIFF');
  assert.equal(optimized.subarray(8, 12).toString('ascii'), 'WEBP');
  assert.ok(
    optimized.length < details.size * 0.3,
    `${asset.optimizedFile} should be at least 70% smaller than ${asset.file}`,
  );
}

