import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const themeRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

const [runtime, css, poster, portrait, panel] = await Promise.all([
  readFile(join(themeRoot, 'src/client/runtime.js'), 'utf8'),
  readFile(join(themeRoot, 'src/client/theme.css'), 'utf8'),
  readFile(join(themeRoot, 'assets/aemeath-poster.png')),
  readFile(join(themeRoot, 'assets/aemeath-portrait.png')),
  readFile(join(themeRoot, 'assets/aemeath-wiki-background.png')),
]);

const dataUrl = (mimeType, buffer) =>
  `data:${mimeType};base64,${buffer.toString('base64')}`;

const bundle = `// Generated by scripts/build-client.mjs. Do not edit directly.\nwindow.__ModuleLoader__.load({\n  id: "@dsh-external/dsh-client-ui-skin-wuthering-aemeath",\n  factory: (require) => {\n    var module = { exports: {} };\n    var exports = module.exports;\n    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });\n\n    const AEMEATH_THEME_CSS = ${JSON.stringify(css)};\n    const AEMEATH_ASSET_POSTER = ${JSON.stringify(dataUrl('image/png', poster))};\n    const AEMEATH_ASSET_PORTRAIT = ${JSON.stringify(dataUrl('image/png', portrait))};\n    const AEMEATH_ASSET_PANEL = ${JSON.stringify(dataUrl('image/png', panel))};\n\n${runtime}\n\n    return module.exports;\n  }\n});\n`;

await mkdir(join(themeRoot, 'lib'), { recursive: true });
await writeFile(join(themeRoot, 'lib/client.js'), bundle, 'utf8');
await writeFile(join(themeRoot, 'lib/index.js'), await readFile(join(themeRoot, 'src/index.js'), 'utf8'), 'utf8');

console.log(`Built lib/client.js (${Buffer.byteLength(bundle).toLocaleString()} bytes)`);
