import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const themeRoot = join(dirname(fileURLToPath(import.meta.url)), '..');

const assetRoute = '/plugins/@dsh-external/dsh-client-ui-skin-wuthering-aemeath/assets';
const assetFiles = {
  poster: 'aemeath-poster.webp',
  portrait: 'aemeath-portrait.webp',
  panel: 'aemeath-wiki-background.webp',
};

const [runtime, css, poster, portrait, panel] = await Promise.all([
  readFile(join(themeRoot, 'src/client/runtime.js'), 'utf8'),
  readFile(join(themeRoot, 'src/client/theme.css'), 'utf8'),
  readFile(join(themeRoot, 'assets', assetFiles.poster)),
  readFile(join(themeRoot, 'assets', assetFiles.portrait)),
  readFile(join(themeRoot, 'assets', assetFiles.panel)),
]);

const assetUrl = (file, buffer) => {
  const revision = createHash('sha1').update(buffer).digest('hex').slice(0, 12);
  return `${assetRoute}/${file}?rev=${revision}`;
};

const bundle = `// Generated by scripts/build-client.mjs. Do not edit directly.\nwindow.__ModuleLoader__.load({\n  id: "@dsh-external/dsh-client-ui-skin-wuthering-aemeath",\n  factory: (require) => {\n    var module = { exports: {} };\n    var exports = module.exports;\n    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });\n\n    const AEMEATH_THEME_CSS = ${JSON.stringify(css)};\n    const AEMEATH_ASSET_POSTER = ${JSON.stringify(assetUrl(assetFiles.poster, poster))};\n    const AEMEATH_ASSET_PORTRAIT = ${JSON.stringify(assetUrl(assetFiles.portrait, portrait))};\n    const AEMEATH_ASSET_PANEL = ${JSON.stringify(assetUrl(assetFiles.panel, panel))};\n\n${runtime}\n\n    return module.exports;\n  }\n});\n`;

await mkdir(join(themeRoot, 'lib'), { recursive: true });
await writeFile(join(themeRoot, 'lib/client.js'), bundle, 'utf8');
await writeFile(join(themeRoot, 'lib/index.js'), await readFile(join(themeRoot, 'src/index.js'), 'utf8'), 'utf8');

console.log(`Built lib/client.js (${Buffer.byteLength(bundle).toLocaleString()} bytes)`);
