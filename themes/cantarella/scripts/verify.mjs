const themeRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const readText = (path) => readFile(join(themeRoot, path), 'utf8');
const packageJson = JSON.parse(await readText('package.json'));
const skin = JSON.parse(await readText('skin.json'));
const sources = JSON.parse(await readText('assets/source.json'));
const patch = await readText('cordis.patch.yml');
const bundle = await readText('lib/client.js');
const hostEntry = await readText('lib/index.js');
const themeCss = await readText('src/client/theme.css');
const themeRuntime = await readText('src/client/runtime.js');
const hostModule = await import(`${pathToFileURL(join(themeRoot, 'lib/index.js')).href}?verify=${Date.now()}`);

const expectedPackage = '@dsh-external/dsh-client-ui-skin-wuthering-cantarella';
assert.equal(packageJson.name, expectedPackage);
assert.equal(packageJson.version, '0.3.0');
assert.equal(packageJson.private, true);
assert.equal(packageJson.license, 'MIT');
assert.equal(packageJson.exports['./client'], './lib/client.js');
assert.ok(packageJson.files.includes('assets/cantarella-portrait.webp'));
assert.ok(packageJson.files.includes('assets/source.json'));
assert.ok(packageJson.files.includes('preview'));
assert.equal(skin.schemaVersion, 1);
assert.equal(skin.id, 'wuthering-cantarella');
assert.equal(skin.package, expectedPackage);
assert.equal(skin.bodyAttr, 'data-dsh-skin-cantarella');
assert.equal(skin.wiring.id, 'ui-skin-wuthering-cantarella');
assert.equal(skin.wiring.bundleWired, true);
assert.equal(skin.license.code, 'MIT');
assert.equal(skin.license.assets, 'SEE-NOTICE');
assert.equal(skin.license.commercialUse, false);
assert.equal(skin.assetsEmbedded, false);
assert.match(patch, /id: ui-skin-wuthering-cantarella/);
assert.ok(patch.includes(`name: '${expectedPackage}'`));
assert.ok(bundle.startsWith('// Generated by scripts/build-client.mjs.'));
assert.ok(bundle.includes(`id: "${expectedPackage}"`));
assert.ok(bundle.includes('window.__ModuleLoader__.load'));
assert.ok(bundle.includes('__DSH_WUTHERING_THEME_HUB__'));
assert.ok(bundle.includes("id: 'wuthering-cantarella'"));
assert.ok(bundle.includes('mount: mountCantarellaTheme'));
assert.ok(bundle.includes('cantarella-theme__refraction'));
assert.ok(bundle.includes('cantarella-theme__glints'));
assert.ok(bundle.includes('cantarella-theme__hud-sonar'));
assert.ok(bundle.includes('cantarella-theme__hud-wave'));
assert.ok(bundle.includes('previousTheme.mount()'));
assert.ok(bundle.includes('observer.disconnect()'));
assert.ok(bundle.includes("body.removeAttribute(CANTARELLA_BODY_ATTR)"));
assert.doesNotMatch(bundle, /data:image\//);
assert.doesNotMatch(bundle, /;base64,/);
assert.equal((bundle.match(/\/assets\/cantarella-portrait\.webp\?rev=[a-f0-9]{12}/g) ?? []).length, 1);
assert.ok(Buffer.byteLength(bundle) < 100_000, `client bundle is too large: ${Buffer.byteLength(bundle)} bytes`);
assert.match(hostEntry, /max-age=31536000, immutable/);
assert.match(hostEntry, /content-type': 'image\/webp'/);
assert.deepEqual(hostModule.inject, ['webServer']);

let assetRoute;
hostModule.apply({
  effect: (register) => register(),
  webServer: {
    register: (route) => {
      assetRoute = route;
      return () => {};
    },
  },
});
assert.equal(assetRoute.kind, 'prefix');
assert.match(assetRoute.path, /\/assets$/);

const requestAsset = async (method, url) => {
  const response = {
    body: undefined,
    headers: undefined,
    status: undefined,
    end(body) { this.body = body; },
    writeHead(status, headers = {}) { this.status = status; this.headers = headers; },
  };
  await assetRoute.handler({ method, url }, response);
  return response;
};

const assetResponse = await requestAsset('GET', `${assetRoute.path}/cantarella-portrait.webp?rev=verify`);
assert.equal(assetResponse.status, 200);
assert.equal(assetResponse.headers['content-type'], 'image/webp');
assert.equal(assetResponse.headers['cache-control'], 'public, max-age=31536000, immutable');
assert.equal(assetResponse.headers['content-length'], assetResponse.body.length);
assert.equal(assetResponse.body.subarray(0, 4).toString('ascii'), 'RIFF');
assert.equal((await requestAsset('HEAD', `${assetRoute.path}/cantarella-portrait.webp`)).body, undefined);
assert.equal((await requestAsset('GET', `${assetRoute.path}/missing.webp`)).status, 404);
assert.equal((await requestAsset('POST', `${assetRoute.path}/cantarella-portrait.webp`)).status, 405);

const sidebarRules = [...themeCss.matchAll(/([^{}]*\[class\*='sidebar'\][^{}]*)\{([^{}]*)\}/g)];
assert.ok(sidebarRules.length > 0, 'expected at least one sidebar theme rule');
for (const [, selector, declarations] of sidebarRules) {
  assert.doesNotMatch(declarations, /backdrop-filter\s*:/, `${selector.trim()} must not capture fixed overlays`);
}

const lightRootRule = themeCss.match(/body\[data-dsh-skin-cantarella\]\s*\{([^{}]*)\}/)?.[1] ?? '';
const lightBaseAlpha = Number(lightRootRule.match(/--dsw-alias-bg-base:\s*rgba\([^,]+,[^,]+,[^,]+,\s*([\d.]+)\)/)?.[1]);
assert.ok(lightBaseAlpha <= 0.35, `light theme base layer must reveal the scene (received ${lightBaseAlpha})`);
assert.match(themeCss, /body\[data-dsh-skin-cantarella\]\[data-ds-dark-theme\]/);
assert.match(themeCss, /cantarella-theme__jellyfish/);
assert.match(themeCss, /@keyframes cantarella-sheen/);
assert.match(themeCss, /@keyframes cantarella-glint/);
assert.match(themeCss, /@keyframes cantarella-sonar/);
assert.match(themeCss, /prefers-reduced-motion: reduce/);
assert.match(themeCss, /data-dsh-wuthering-performance='economy'/);
assert.match(themeCss, /contain: strict/);
assert.match(themeCss, /animation: none !important/);
assert.match(themeRuntime, /fullEffects \? 5 : 2/);
assert.match(themeRuntime, /if \(fullEffects\) \{[\s\S]*cantarella-theme__bubbles/);
assert.match(themeRuntime, /if \(fullEffects\) \{[\s\S]*cantarella-theme__glints/);
