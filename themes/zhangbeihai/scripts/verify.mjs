let assetRoute;
hostModule.apply({
  effect: (register) => register(),
  webServer: {
    register: (route) => {
      assetRoute = route;
      return () => {};
    },
  },
});
assert.equal(assetRoute.kind, 'prefix');
assert.match(assetRoute.path, /\/assets$/);

const requestAsset = async (method, url) => {
  const response = {
    body: undefined,
    headers: undefined,
    status: undefined,
    end(body) { this.body = body; },
    writeHead(status, headers = {}) { this.status = status; this.headers = headers; },
  };
  await assetRoute.handler({ method, url }, response);
  return response;
};

const assetResponse = await requestAsset('GET', `${assetRoute.path}/zhangbeihai-command.webp?rev=verify`);
assert.equal(assetResponse.status, 200);
assert.equal(assetResponse.headers['content-type'], 'image/webp');
assert.equal(assetResponse.headers['cache-control'], 'public, max-age=31536000, immutable');
assert.equal(assetResponse.headers['content-length'], assetResponse.body.length);
assert.equal(assetResponse.body.subarray(0, 4).toString('ascii'), 'RIFF');
const backgroundResponse = await requestAsset('GET', `${assetRoute.path}/zhangbeihai-background.png?rev=verify`);
assert.equal(backgroundResponse.status, 200);
assert.equal(backgroundResponse.headers['content-type'], 'image/png');
assert.equal(backgroundResponse.body.subarray(1, 4).toString('ascii'), 'PNG');
const characterResponse = await requestAsset('GET', `${assetRoute.path}/zhangbeihai-character-cutout-v6.png?rev=verify`);
assert.equal(characterResponse.status, 200);
assert.equal(characterResponse.headers['content-type'], 'image/png');
assert.equal(characterResponse.body.subarray(1, 4).toString('ascii'), 'PNG');
