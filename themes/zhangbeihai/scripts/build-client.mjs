import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const themeRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = join(themeRoot, '..', '..');
const assetRoute = '/plugins/@dsh-external/dsh-client-ui-skin-threebody-zhangbeihai/assets';
const previewFile = 'zhangbeihai-command.webp';
const backgroundFile = 'zhangbeihai-background.png';
const characterFile = 'zhangbeihai-character-cutout-v6.png';

const [hubRuntime, runtime, css, preview, background, character] = await Promise.all([
  readFile(join(repoRoot, 'shared', 'theme-hub-runtime.js'), 'utf8'),
  readFile(join(themeRoot, 'src/client/runtime.js'), 'utf8'),
  readFile(join(themeRoot, 'src/client/theme.css'), 'utf8'),
  readFile(join(themeRoot, 'assets', previewFile)),
  readFile(join(themeRoot, 'assets', backgroundFile)),
  readFile(join(themeRoot, 'assets', characterFile)),
]);

const revisionUrl = (file, content) => {
  const revision = createHash('sha1').update(content).digest('hex').slice(0, 12);
  return `${assetRoute}/${file}?rev=${revision}`;
};

const previewUrl = revisionUrl(previewFile, preview);
const backgroundUrl = revisionUrl(backgroundFile, background);
const characterUrl = revisionUrl(characterFile, character);
const bundle = `// Generated by scripts/build-client.mjs. Do not edit directly.\nwindow.__ModuleLoader__.load({\n  id: "@dsh-external/dsh-client-ui-skin-threebody-zhangbeihai",\n  factory: (require) => {\n    var module = { exports: {} };\n    var exports = module.exports;\n    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });\n\n    const ZHANGBEIHAI_THEME_CSS = ${JSON.stringify(css)};\n    const ZHANGBEIHAI_ASSET_PREVIEW = ${JSON.stringify(previewUrl)};\n    const ZHANGBEIHAI_ASSET_BACKGROUND = ${JSON.stringify(backgroundUrl)};\n    const ZHANGBEIHAI_ASSET_CHARACTER = ${JSON.stringify(characterUrl)};\n\n${hubRuntime}\n\n${runtime}\n\n    return module.exports;\n  }\n});\n`;

await mkdir(join(themeRoot, 'lib'), { recursive: true });
await writeFile(join(themeRoot, 'lib/client.js'), bundle, 'utf8');
await writeFile(join(themeRoot, 'lib/index.js'), await readFile(join(themeRoot, 'src/index.js'), 'utf8'), 'utf8');
console.log(`Built lib/client.js (${Buffer.byteLength(bundle).toLocaleString()} bytes)`);
