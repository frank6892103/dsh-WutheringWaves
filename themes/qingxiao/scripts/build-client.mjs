import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const themeRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const repoRoot = join(themeRoot, '..', '..');
const assetRoute = '/plugins/@dsh-external/dsh-client-ui-skin-wuthering-qingxiao/assets';
const posterFile = 'qingxiao-poster.webp';
const characterFile = 'qingxiao-character.png';

const [hubRuntime, runtime, css, poster, character] = await Promise.all([
  readFile(join(repoRoot, 'shared', 'theme-hub-runtime.js'), 'utf8'),
  readFile(join(themeRoot, 'src/client/runtime.js'), 'utf8'),
  readFile(join(themeRoot, 'src/client/theme.css'), 'utf8'),
  readFile(join(themeRoot, 'assets', posterFile)),
  readFile(join(themeRoot, 'assets', characterFile)),
]);

const revisionOf = (asset) => createHash('sha1').update(asset).digest('hex').slice(0, 12);
const posterUrl = `${assetRoute}/${posterFile}?rev=${revisionOf(poster)}`;
const characterUrl = `${assetRoute}/${characterFile}?rev=${revisionOf(character)}`;
const bundle = `// Generated by scripts/build-client.mjs. Do not edit directly.\nwindow.__ModuleLoader__.load({\n  id: "@dsh-external/dsh-client-ui-skin-wuthering-qingxiao",\n  factory: (require) => {\n    var module = { exports: {} };\n    var exports = module.exports;\n    Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });\n\n    const QINGXIAO_THEME_CSS = ${JSON.stringify(css)};\n    const QINGXIAO_ASSET_POSTER = ${JSON.stringify(posterUrl)};\n    const QINGXIAO_ASSET_CHARACTER = ${JSON.stringify(characterUrl)};\n\n${hubRuntime}\n\n${runtime}\n\n    return module.exports;\n  }\n});\n`;

await mkdir(join(themeRoot, 'lib'), { recursive: true });
await writeFile(join(themeRoot, 'lib/client.js'), bundle, 'utf8');
await writeFile(join(themeRoot, 'lib/index.js'), await readFile(join(themeRoot, 'src/index.js'), 'utf8'), 'utf8');
console.log(`Built lib/client.js (${Buffer.byteLength(bundle).toLocaleString()} bytes)`);
