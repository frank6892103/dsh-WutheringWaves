const requestAsset = async (method, url) => {
  const response = {
    body: undefined,
    headers: undefined,
    status: undefined,
    end(body) { this.body = body; },
    writeHead(status, headers = {}) { this.status = status; this.headers = headers; },
  };
  await assetRoute.handler({ method, url }, response);
  return response;
};

const sanctuaryResponse = await requestAsset('GET', `${assetRoute.path}/ronova-sanctuary.webp?rev=verify`);
assert.equal(sanctuaryResponse.status, 200);
assert.equal(sanctuaryResponse.headers['content-type'], 'image/webp');
assert.equal(sanctuaryResponse.headers['cache-control'], 'public, max-age=31536000, immutable');
assert.equal(sanctuaryResponse.headers['content-length'], sanctuaryResponse.body.length);
assert.equal(sanctuaryResponse.body.subarray(0, 4).toString('ascii'), 'RIFF');
const characterResponse = await requestAsset('GET', `${assetRoute.path}/ronova-character.png?rev=verify`);
assert.equal(characterResponse.status, 200);
assert.equal(characterResponse.headers['content-type'], 'image/png');
assert.equal(characterResponse.body.subarray(1, 4).toString('ascii'), 'PNG');
assert.equal((await requestAsset('HEAD', `${assetRoute.path}/ronova-sanctuary.webp`)).body, undefined);
assert.equal((await requestAsset('HEAD', `${assetRoute.path}/ronova-character.png`)).body, undefined);
assert.equal((await requestAsset('GET', `${assetRoute.path}/missing.webp`)).status, 404);
